-- Regenerates Core/BugFiles.lua from Tomte.toc. Run from the AddOns folder: lua Tomte/tools/bugfiles.lua
-- tests/test_bugreport.lua fails when the TOC and the list differ.
local files = {}
for line in io.lines("Tomte/Tomte.toc") do
	local file = line:match("^([%w_/\\]+%.lua)%s*$")
	if file then
		files[#files + 1] = "\t\"" .. file:gsub("\\", "/") .. "\","
	end
end
local out = assert(io.open("Tomte/Core/BugFiles.lua", "wb"))
out:write("local addonName, ns = ...\n\n")
out:write("-- Tomte's own Lua files, in TOC order (generated by tools/bugfiles.lua; tests/test_bugreport.lua checks it).\n")
out:write("-- The bug report uses them to recognise an error path Lua shortened to \"...<end of path>\".\n")
out:write("ns.BUG_FILES = {\n" .. table.concat(files, "\n") .. "\n}\n")
out:close()
print(("Core/BugFiles.lua: %d files"):format(#files))
