"""Builds Data/Forever/MinimapTiles.lua: the game's own minimap tile files for both continents on World of
Warcraft: Forever, which the Tomte map draws when zoomed in close (Modules/Map/Mini.lua). No art is shipped: the table
names files the client already has.

Each continent's WDT file (its FileDataID is the Map table's WdtFileDataID) lists, for each of its 64 x 64 terrain
tiles, the files that make it up; the eighth of them is the tile's minimap picture. Read from the MAIN chunk (bit 1:
the tile has terrain) and the MAID chunk (8 FileDataIDs per tile). The approach follows OpenMap's
tools/map-data/minimap.py (MIT, github.com/openmap-world/openmap); written anew here.

From the Tomte folder:
    python -I tools/minimaptiles.py <build, e.g. 1.60.1.70938> [cache folder]
Downloads the Map table and the two WDT files from wago.tools (one at a time) into the cache folder.
"""
import os
import struct
import sys
import time
import urllib.request

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import wago  # noqa: E402

OUT = os.path.join("Data", "Forever", "MinimapTiles.lua")
CONTINENTS = (0, 1)  # instance map IDs: Eastern Kingdoms, Kalimdor
GRID = 64
MINIMAP_SLOT = 7  # MAID entries: root, obj0, obj1, tex0, lod, map texture, map normal, minimap


def download(url, path):
    if os.path.exists(path) and os.path.getsize(path) > 64:
        return
    print("downloading", url)
    req = urllib.request.Request(url, headers={"User-Agent": wago.UA})
    with urllib.request.urlopen(req) as resp:
        body = resp.read()
    # wago answers a missing file with 200 and an (almost) empty body.
    if len(body) <= 64:
        raise SystemExit("empty answer for %s (wrong build or file ID?)" % url)
    with open(path, "wb") as f:
        f.write(body)
    time.sleep(0.3)  # one request at a time, gently: bursts get empty answers


def chunks(data):
    """{ tag: bytes } of a chunked file; tags are stored reversed (b"NIAM" is MAIN)."""
    out, pos = {}, 0
    while pos + 8 <= len(data):
        tag = data[pos:pos + 4][::-1].decode("ascii", "replace")
        size = struct.unpack_from("<I", data, pos + 4)[0]
        out[tag] = data[pos + 8:pos + 8 + size]
        pos += 8 + size
    return out


def tiles(wdt):
    """{ x * 64 + y: minimap FileDataID } for the tiles with terrain; x runs east, y south."""
    c = chunks(wdt)
    main, maid = c.get("MAIN"), c.get("MAID")
    if not main or not maid:
        raise SystemExit("WDT without MAIN or MAID")
    found = {}
    for n in range(GRID * GRID):
        y, x = divmod(n, GRID)
        if struct.unpack_from("<I", main, n * 8)[0] & 1:
            fid = struct.unpack_from("<8I", maid, n * 32)[MINIMAP_SLOT]
            if fid:
                found[x * GRID + y] = fid
    return found


def main():
    if len(sys.argv) < 2:
        raise SystemExit(__doc__)
    build = sys.argv[1]
    folder = wago.folder_from_argv("tomte-minimaptiles-")
    os.makedirs(folder, exist_ok=True)
    maps = {int(r["ID"]): r for r in wago.load(folder, ["Map"], build)["Map"]}
    lines = [
        "local addonName, ns = ...",
        "",
        "-- Generated by tools/minimaptiles.py from build %s: don't edit. The game's own minimap tile files, read from" % build,
        "-- each continent's WDT file (approach after OpenMap's tools/map-data/minimap.py, MIT).",
        "-- minimapTiles: [instance map ID] = { [x * 64 + y] = FileDataID }, tile x running east and y south, each tile",
        "-- 1600/3 yards across; tile 32, 32 has its north-west corner at world 0, 0. Drawn by Modules/Map/Mini.lua.",
        "",
        "ns.Content_Register(ns.CONTENT_FOREVER, \"minimapTiles\", {",
    ]
    total = 0
    for cont in CONTINENTS:
        fid = int(maps[cont]["WdtFileDataID"])
        path = os.path.join(folder, "%d.wdt" % fid)
        download("https://wago.tools/api/casc/%d?download&version=%s" % (fid, build), path)
        with open(path, "rb") as f:
            found = tiles(f.read())
        total += len(found)
        lines.append("\t[%d] = { -- %s, WDT %d" % (cont, maps[cont]["MapName_lang"], fid))
        row = []
        for key in sorted(found):
            row.append("[%d]=%d," % (key, found[key]))
            if len(row) == 8:
                lines.append("\t\t" + " ".join(row))
                row = []
        if row:
            lines.append("\t\t" + " ".join(row))
        lines.append("\t},")
    lines.append("})")
    with open(OUT, "w", encoding="utf-8", newline="\r\n") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote %s: %d tiles" % (OUT, total))


if __name__ == "__main__":
    main()
