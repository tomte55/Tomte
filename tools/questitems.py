"""Builds Data/Forever/QuestItems.lua: which quests each quest item belongs to, on World of Warcraft: Forever.

From QuestieDB's Forever data (github.com/Questie/QuestieDB, data/Forever/foreverQuestDB.lua at the commit below). Only
facts are taken: item and quest IDs, how the item belongs to the quest, the quest's title and who can take it. QuestieDB's
LICENSE.md lets others copy under GPLv3 terms (Tomte's license); credited in README's Credits.

Fetch the file into a folder of its own, then, from the Tomte folder:
    python -I tools/questitems.py <folder> <QuestieDB commit the file came from>
It's read as text by the small parser below and never run.
"""
import os
import re
import sys

OUT = os.path.join("Data", "Forever", "QuestItems.lua")

# Quest fields (QuestieDB's questKeys, 1-based).
NAME, RACES, CLASSES, OBJECTIVES, SOURCE_ITEM, REQUIRED_ITEMS = 1, 6, 7, 10, 11, 21
ITEM_OBJECTIVES = 3  # within objectives: { {itemID, text, icon}, ... }


class Parser:
    """A Lua table literal as Python lists: numbers, strings, nil (None) and { ... } (list; keyed entries are skipped)."""

    TOKEN = re.compile(r'\s*(?:(\{)|(\})|(,)|(nil)|(true|false)|(-?\d+(?:\.\d+)?)|"((?:[^"\\]|\\.)*)"|\'((?:[^\'\\]|\\.)*)\')')

    def __init__(self, text):
        self.text, self.pos = text, 0

    def next(self):
        m = self.TOKEN.match(self.text, self.pos)
        if not m:
            raise ValueError("can't read at %d: %r" % (self.pos, self.text[self.pos:self.pos + 40]))
        self.pos = m.end()
        return m

    def value(self):
        m = self.next()
        if m.group(1):
            return self.table()
        if m.group(4):
            return None
        if m.group(5):
            return m.group(5) == "true"
        if m.group(6):
            n = m.group(6)
            return float(n) if "." in n else int(n)
        s = m.group(7) if m.group(7) is not None else m.group(8)
        return re.sub(r"\\(.)", r"\1", s)

    KEY = re.compile(r"\s*\[(-?\d+)\]\s*=")

    def table(self):
        out = []
        while True:
            key = self.KEY.match(self.text, self.pos)
            if key:  # a keyed entry (zone coordinates and such): read past it, not needed here
                self.pos = key.end()
                self.value()
                continue
            save = self.pos
            m = self.next()
            if m.group(2):
                return out
            if m.group(3):
                continue
            self.pos = save
            out.append(self.value())


def field(row, index):
    return row[index - 1] if len(row) >= index else None


def read_quests(path):
    text = open(path, encoding="utf-8").read()
    start = text.index("questData = [[return {")
    body = text[start:]
    quests = {}
    for m in re.finditer(r"^\[(\d+)\] = (\{.*\}),\s*$", body, re.M):
        quests[int(m.group(1))] = Parser(m.group(2)).value()
    return quests


def lua_string(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    if len(sys.argv) < 3:
        sys.exit(__doc__)
    folder, commit = sys.argv[1], sys.argv[2]
    quests = read_quests(os.path.join(folder, "foreverQuestDB.lua"))
    items = {}  # itemID -> {questID: kind}

    def add(item, quest, kind):
        if isinstance(item, int) and item > 0:
            items.setdefault(item, {}).setdefault(quest, kind)

    for qid, row in quests.items():
        objectives = field(row, OBJECTIVES)
        if isinstance(objectives, list) and len(objectives) >= ITEM_OBJECTIVES:
            for entry in objectives[ITEM_OBJECTIVES - 1] or []:
                if isinstance(entry, list) and entry:
                    add(entry[0], qid, "o")
        add(field(row, SOURCE_ITEM), qid, "g")
        for item in field(row, REQUIRED_ITEMS) or []:
            add(item, qid, "r")

    used = sorted({q for qs in items.values() for q in qs})
    lines = [
        "local addonName, ns = ...",
        "",
        "-- Generated by tools/questitems.py: don't edit. From QuestieDB's Forever data (github.com/Questie/QuestieDB,",
        "-- data/Forever/foreverQuestDB.lua, commit %s), copied under GPLv3 terms as its LICENSE.md allows." % commit,
        "-- questItems: [itemID] = \"questID:kind,...\", kind o (a quest objective), g (the quest gives it to you) or r (the",
        "-- quest needs it without counting it). questItemQuests: [questID] = { title (English), races, classes }: the race",
        "-- and class bit masks of who can take it (bit n-1 for race or class ID n; 0 for anyone). Read by Gold & value's",
        "-- markers (Modules/Value/Markers.lua).",
        "",
        "ns.Content_Register(ns.CONTENT_FOREVER, \"questItems\", {",
    ]
    for item in sorted(items):
        lines.append("\t[%d] = \"%s\"," % (item, ",".join("%d:%s" % (q, k) for q, k in sorted(items[item].items()))))
    lines.append("})")
    lines.append("")
    lines.append("ns.Content_Register(ns.CONTENT_FOREVER, \"questItemQuests\", {")
    for q in used:
        row = quests[q]
        lines.append("\t[%d] = { %s, %d, %d }," % (q, lua_string(field(row, NAME) or "?"), int(field(row, RACES) or 0),
                                                  int(field(row, CLASSES) or 0)))
    lines.append("})")
    with open(OUT, "w", encoding="utf-8", newline="\r\n") as f:
        f.write("\n".join(lines) + "\n")
    print("%s: %d items, %d quests" % (OUT, len(items), len(used)))


if __name__ == "__main__":
    main()
