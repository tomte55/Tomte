"""Autocorrect: builds Modules/Autocorrect/Words.lua (the English word list) from SCOWL.

SCOWL (Spell Checker Oriented Word Lists) by Kevin Atkinson, release 2020.12.07:
  https://downloads.sourceforge.net/project/wordlist/SCOWL/2020.12.07/scowl-2020.12.07.tar.gz
Unpack it anywhere, then from the AddOns folder:
  python -I Tomte/tools/autocorrect_words.py <path>/scowl-2020.12.07/final Tomte/Modules/Autocorrect/Words.lua

What it writes (pure data, one long string per list, words separated by newlines):
  ns.AUTOCORRECT_WORDS[level]     lowercase words of that SCOWL size (english + american + british), each word only
                                  at its lowest level; the level is how common it is (10 most common .. 60 rare)
  ns.AUTOCORRECT_UPPER            words always written with a capital (English, Monday), sizes up to 50
  ns.AUTOCORRECT_CONTRACTIONS     contractions (don't, I'm), sizes up to 50
Only plain ASCII words are kept: the edit box works in bytes, and accented words are left alone anyway.
"""

import re
import sys
from pathlib import Path

LEVELS = [10, 20, 35, 40, 50, 55, 60]
UPPER_MAX = 50
CONTRACTIONS_MAX = 50
VARIETIES = ["english", "american", "british"]
LOWER_WORD = re.compile(r"^[a-z]+('[a-z]+)?$")
UPPER_WORD = re.compile(r"^[A-Z][a-z]+$")
CONTRACTION = re.compile(r"^[A-Za-z]+'[a-z]+$")

COPYRIGHT = """SCOWL is Copyright 2000-2018 by Kevin Atkinson.
Permission to use, copy, modify, distribute and sell these word lists, the associated scripts, the output created
from the scripts, and its documentation for any purpose is hereby granted without fee, provided that the above
copyright notice appears in all copies and that both that copyright notice and this permission notice appear in
supporting documentation. Kevin Atkinson makes no representations about the suitability of this array for any
purpose. It is provided "as is" without express or implied warranty."""


def read(folder, kind, level):
    words = []
    for variety in VARIETIES:
        path = folder / f"{variety}-{kind}.{level}"
        if path.exists():
            words += path.read_text(encoding="latin-1").split()
    return words


def lua_string(words):
    body = "\n".join(words)
    assert "]==]" not in body
    return "[==[\n" + body + "\n]==]"


def main():
    folder, out = Path(sys.argv[1]), Path(sys.argv[2])
    seen = set()
    levels = {}
    for level in LEVELS:
        words = sorted({w for w in read(folder, "words", level) if LOWER_WORD.match(w) and w not in seen})
        seen.update(words)
        levels[level] = words
        print(f"level {level}: {len(words)} words ({len(seen)} so far)")

    upper = set()
    contractions = set()
    for level in LEVELS:
        if level <= UPPER_MAX:
            upper.update(w for w in read(folder, "upper", level) if UPPER_WORD.match(w))
        if level <= CONTRACTIONS_MAX:
            contractions.update(w for w in read(folder, "contractions", level) if CONTRACTION.match(w))
    upper, contractions = sorted(upper), sorted(contractions)
    print(f"upper: {len(upper)}, contractions: {len(contractions)}")

    lines = [
        "local addonName, ns = ...",
        "",
        "-- Autocorrect: the English word list. Generated by tools/autocorrect_words.py from SCOWL 2020.12.07; don't",
        "-- edit by hand, change the tool and regenerate.",
        "--",
    ]
    lines += ["-- " + line if line else "--" for line in COPYRIGHT.splitlines()]
    lines += ["", "ns.AUTOCORRECT_WORDS = {"]
    for level in LEVELS:
        lines.append(f"\t[{level}] = {lua_string(levels[level])},")
    lines += ["}", "", "ns.AUTOCORRECT_UPPER = " + lua_string(upper), "",
              "ns.AUTOCORRECT_CONTRACTIONS = " + lua_string(contractions), ""]
    out.write_bytes("\r\n".join(lines).encode("ascii"))
    print(f"wrote {out} ({out.stat().st_size // 1024} KB)")


if __name__ == "__main__":
    main()
