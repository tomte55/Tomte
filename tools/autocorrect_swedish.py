"""Autocorrect: builds Modules/Autocorrect/WordsSwedish.lua (the Swedish word list) from FrequencyWords.

FrequencyWords by Hermit Dave, the 2018 OpenSubtitles counts (content CC BY-SA 4.0), Swedish top 50,000:
  https://raw.githubusercontent.com/hermitdave/FrequencyWords/0e18d96445b6cb9a8ca34ab2f88b5056785ac378/content/2018/sv/sv_50k.txt
Subtitles are spoken language, close to what people write in chat. From the AddOns folder:
  python -I Tomte/tools/autocorrect_swedish.py <path>/sv_50k.txt Tomte/Modules/Autocorrect/WordsSwedish.lua

What it writes (pure data, one long string per list, words separated by newlines):
  ns.AUTOCORRECT_SV_WORDS[level]  lowercase words in bands of how common they are, on the English list's scale (10 the
                                  most common .. 60 rare): the first 1,000 are 10, then 20, 35, 50 and 60
  ns.AUTOCORRECT_SV_LETTERS       "ar>är pa>på ...": a word written without its å, ä, ö or é where the spelling with
                                  them is at least LETTERS_RATIO times as common. The plain spelling is a typo, so it
                                  is left out of the word list (subtitles have a few: "garna" for "gärna").
Only words of a-z, å, ä, ö and é are kept; one-letter words only when they are words (i, å, ö).
"""

import re
import sys
from pathlib import Path

BANDS = [(1000, 10), (5000, 20), (15000, 35), (30000, 50)]  # rank up to, level; the rest are 60
RARE = 60
LETTERS_RATIO = 20
WORD = re.compile(r"^[a-zåäöé]+$")
SINGLE = {"i", "å", "ö"}
WITH = {"a": "åä", "o": "ö", "e": "é"}

CREDIT = """Swedish word frequencies from FrequencyWords by Hermit Dave (https://github.com/hermitdave/FrequencyWords),
counted from OpenSubtitles (http://www.opensubtitles.org), licensed CC BY-SA 4.0
(https://creativecommons.org/licenses/by-sa/4.0/). This file is an adaptation of that list, shared under the same
license as part of Tomte (GPL-3.0; CC BY-SA 4.0 is one-way compatible with it)."""


def read(path):
    freq, order = {}, []
    for line in path.read_text(encoding="utf-8", errors="replace").splitlines():
        parts = line.split()
        if len(parts) != 2 or not parts[1].isdigit():
            continue
        word = parts[0].lower()
        if not WORD.match(word) or (len(word) == 1 and word not in SINGLE) or word in freq:
            continue
        freq[word] = int(parts[1])
        order.append(word)
    return freq, order


def variants(word):
    out = [""]
    for ch in word:
        out = [o + c for o in out for c in ch + WITH.get(ch, "")]
    return [v for v in out if v != word]


def letters(freq):
    """{plain: with} where the spelling with å, ä, ö or é is far more common than the plain one."""
    fixes = {}
    for word, count in freq.items():
        if re.search("[åäöé]", word):
            continue
        best = max(variants(word), key=lambda v: freq.get(v, 0), default=None)
        if best and freq.get(best, 0) >= LETTERS_RATIO * count:
            fixes[word] = best
    return fixes


def level_of(rank):
    for limit, level in BANDS:
        if rank <= limit:
            return level
    return RARE


def lua_string(words):
    body = "\n".join(words)
    if "]==]" in body:
        raise ValueError("word list contains the long-string closer")
    return "[==[\n" + body + "\n]==]"


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    source, target = Path(sys.argv[1]), Path(sys.argv[2])
    freq, order = read(source)
    fixes = letters(freq)
    bands = {}
    rank = 0
    for word in order:
        if word in fixes:
            continue
        rank += 1
        bands.setdefault(level_of(rank), []).append(word)
    out = ["local addonName, ns = ...", "",
           "-- Autocorrect: the Swedish word list. Generated by tools/autocorrect_swedish.py from FrequencyWords; don't",
           "-- edit by hand, change the tool and regenerate.", "--"]
    out += ["-- " + line for line in CREDIT.splitlines()]
    out += ["", "ns.AUTOCORRECT_SV_WORDS = {"]
    for level in sorted(bands):
        out.append(f"\t[{level}] = {lua_string(sorted(bands[level]))},")
    out.append("}")
    out.append("")
    pairs = " ".join(f"{plain}>{fixes[plain]}" for plain in sorted(fixes))
    out.append("-- A word written without its å, ä, ö or é: the spelling with them (only in a line that is Swedish).")
    out.append(f"ns.AUTOCORRECT_SV_LETTERS = {lua_string([pairs])}")
    out.append("")
    # CRLF like every Lua file here (Lua reads a line break in a long string as \n either way).
    target.write_bytes("\n".join(out).replace("\n", "\r\n").encode("utf-8"))
    total = sum(len(b) for b in bands.values())
    print(f"{target}: {total} words, {len(fixes)} letter fixes")


if __name__ == "__main__":
    main()
