"""Builds Data/Forever/MapReveal.lua: every explored-area piece of every map on World of Warcraft: Forever, explored
or not. The Tomte map draws each zone from these pieces (Modules/Map/Art.lua): a zone's base picture also shows its
neighbours and a parchment frame, while its pieces cover only its own land. The game's API lists only the pieces you
have explored (C_MapExplorationInfo.GetExploredMapTextures); the tables list all of them.

From the WorldMapOverlay and WorldMapOverlayTile tables (layer 0), for the map art the client's maps use
(UiMapXMapArt). The idea of drawing a zone from its pieces follows OpenMap (MIT, github.com/openmap-world/openmap,
its Reveal.lua and render.py's own_land); written anew here.

From the Tomte folder:
    python -I tools/mapreveal.py <build, e.g. 1.60.1.70938> [cache folder]
"""
import os
import sys
from collections import defaultdict

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import wago  # noqa: E402

OUT = os.path.join("Data", "Forever", "MapReveal.lua")
MAP_ZONE = 3  # UiMap.Type


def main():
    if len(sys.argv) < 2:
        raise SystemExit(__doc__)
    build = sys.argv[1]
    folder = wago.folder_from_argv("tomte-mapreveal-")
    os.makedirs(folder, exist_ok=True)
    data = wago.load(folder, ["WorldMapOverlay", "WorldMapOverlayTile", "UiMapXMapArt", "UiMap"], build)
    used = {int(r["UiMapArtID"]) for r in data["UiMapXMapArt"]}
    tiles = defaultdict(list)
    for t in data["WorldMapOverlayTile"]:
        if int(t["LayerIndex"]) == 0:
            tiles[int(t["WorldMapOverlayID"])].append((int(t["RowIndex"]), int(t["ColIndex"]), int(t["FileDataID"])))
    pieces = defaultdict(list)
    for o in data["WorldMapOverlay"]:
        art, oid = int(o["UiMapArtID"]), int(o["ID"])
        if art not in used or not tiles[oid]:
            continue
        files = [fid for _, _, fid in sorted(tiles[oid])]
        pieces[art].append((int(o["OffsetX"]), int(o["OffsetY"]), int(o["TextureWidth"]), int(o["TextureHeight"]),
                            files, oid))
    lines = [
        "local addonName, ns = ...",
        "",
        "-- Generated by tools/mapreveal.py from build %s: don't edit. Every explored-area piece of each map's art," % build,
        "-- explored or not (WorldMapOverlay, WorldMapOverlayTile layer 0).",
        "-- mapReveal: [uiMapArtID] = { { x, y, width, height, fileDataID, ... } }: a piece's offset and size in the",
        "-- map's art pixels and its files row by row, cut in 256-pixel tiles as C_MapExplorationInfo's pieces are.",
        "-- A zone's art without any pieces has an empty list: a capital (on this client the game doesn't flag them as",
        "-- cities), whose land its zone's art already draws. Drawn by Modules/Map/Art.lua.",
        "",
        "ns.Content_Register(ns.CONTENT_FOREVER, \"mapReveal\", {",
    ]
    zones = {int(r["ID"]) for r in data["UiMap"] if int(r["Type"]) == MAP_ZONE}
    bare = {int(r["UiMapArtID"]) for r in data["UiMapXMapArt"] if int(r["UiMapID"]) in zones} - set(pieces)
    count = 0
    for art in sorted(bare):
        lines.append("	[%d] = {}," % art)
    for art in sorted(pieces):
        lines.append("\t[%d] = {" % art)
        for x, y, w, h, files, _ in sorted(pieces[art], key=lambda p: p[5]):
            lines.append("\t\t{ %d, %d, %d, %d, %s }," % (x, y, w, h, ", ".join(str(f) for f in files)))
            count += 1
        lines.append("\t},")
    lines.append("})")
    with open(OUT, "w", encoding="utf-8", newline="\r\n") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote %s: %d pieces on %d maps" % (OUT, count, len(pieces)))


if __name__ == "__main__":
    main()
