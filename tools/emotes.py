"""Builds Modules/EmoteWheel/Generated.lua (which emotes act out an animation and which have a voice line) from the
client's EmotesText, Emotes and EmotesTextSound tables, read from wago.tools CSV exports. Dev-only, not in the release
zip.

    python -I tools/emotes.py <build> [csv-dir]

<build> is the client build, e.g. 12.1.5.70391. With no csv-dir the tables are downloaded into a new, empty temp
folder. Rerun after a patch that adds emotes; an emote the file doesn't know just shows no marks in the editor.

Emotes are keyed by their token (EmotesText.Name, the game's EMOTE<i>_TOKEN), which is the same in every language.
An emote acts out when its Emotes row has an animation. A voice line is per race and sex (and a few per class: Demon
Hunters); an emote every race and sex has is `true`, else a set of "race-sex" keys ("race-sex-class" for a
class-only line), with sex 0 male and 1 female as in the table.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))  # the -I flag leaves the script folder off sys.path
import wago

TABLES = ["EmotesText", "Emotes", "EmotesTextSound"]
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "Modules", "EmoteWheel", "Generated.lua")
NO_ANIM = {"", "0", "-1"}


def main():
    if len(sys.argv) < 2:
        print(__doc__)
        sys.exit(1)
    build = sys.argv[1]
    data = wago.load(wago.folder_from_argv("tomte_emotes_"), TABLES, build)
    emotes = {r["ID"]: r for r in data["Emotes"]}
    token = {r["ID"]: r["Name"] for r in data["EmotesText"]}

    acts = set()
    for row in data["EmotesText"]:
        emote = emotes.get(row["EmoteID"])
        if row["EmoteID"] != "0" and emote and emote["AnimID"] not in NO_ANIM:
            acts.add(row["Name"])

    voice = {}
    everyone = set()
    for row in data["EmotesTextSound"]:
        name = token.get(row["EmotesTextID"])
        if not name:
            continue
        key = "%s-%s" % (row["RaceID"], row["SexID"])
        if row["ClassID"] != "0":
            key += "-" + row["ClassID"]
        else:
            everyone.add(key)
        voice.setdefault(name, set()).add(key)

    lines = ["local addonName, ns = ...", "",
             "-- Generated by tools/emotes.py from the client's EmotesText, Emotes and EmotesTextSound tables "
             "(wago.tools, build %s). Do not edit." % build,
             "-- EMOTEWHEEL_ACTS[token]: the emote has an animation. EMOTEWHEEL_VOICE[token]: true for a voice line "
             "for every race and sex,",
             "-- else { [\"race-sex\"] = true } (sex 0 male, 1 female; \"race-sex-class\" for a class's own line).",
             "ns.EMOTEWHEEL_ACTS = {"]
    names = sorted(acts)
    for n in range(0, len(names), 8):
        lines.append("\t" + " ".join("%s = true," % t for t in names[n:n + 8]))
    lines.append("}")
    lines.append("ns.EMOTEWHEEL_VOICE = {")
    for name in sorted(voice):
        keys = voice[name]
        if everyone <= keys:
            lines.append("\t%s = true," % name)
        else:
            ordered = sorted(keys, key=lambda k: [int(p) for p in k.split("-")])
            lines.append("\t%s = {" % name)
            for n in range(0, len(ordered), 10):
                lines.append("\t\t" + " ".join("[\"%s\"] = true," % k for k in ordered[n:n + 10]))
            lines.append("\t},")
    lines.append("}")
    with open(OUT, "w", encoding="utf-8", newline="\r\n") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote %s: %d emotes act out, %d have a voice line (%d for every race and sex)" % (
        os.path.normpath(OUT), len(acts), len(voice), sum(1 for k in voice.values() if everyone <= k)))


if __name__ == "__main__":
    main()
