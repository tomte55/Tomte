"""Builds Modules/Chat/RecipesForever.lua (every crafting recipe of World of Warcraft: Forever per profession, with the
item it makes) from the client's spell tables, read from wago.tools CSV exports. Dev-only, not in the release zip.

    python -I tools/recipes.py <build> [csv-dir]

<build> is a Forever client build, e.g. 1.60.1.70790. With no csv-dir the tables are downloaded into a new, empty
temp folder. Tables: SkillLineAbility, SkillLine, SpellEffect, SpellName.

Trade Filter uses it to tell a request for a recipe you don't know ("LF enchanter, Enchant Boots - Minor Speed") from
one you can do. Forever's profession window lists only the recipes you know, so the game can't name the rest; the
names are looked up from these spell IDs at run time (C_Spell.GetSpellName), so they match any client language.

A recipe is a spell on a profession's skill line (SkillLine.ParentSkillLineID folded in, as tools/materials.py does)
that makes an item (CREATE_ITEM, 24) or enchants one (ENCHANT_ITEM, 53). Profession ranks, Disenchant and the like
have neither and are left out.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))  # the -I flag leaves the script folder off sys.path
import wago

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "Modules", "Chat", "RecipesForever.lua")
TABLES = ["SkillLineAbility", "SkillLine", "SpellEffect", "SpellName"]
CREATE_ITEM, ENCHANT_ITEM = 24, 53
# The professions that craft, as in tools/materials.py (Forever has First Aid, 129).
PROFESSIONS = {129, 164, 165, 171, 182, 185, 186, 197, 202, 333, 393, 755, 773}
# Spot checks printed after writing: spell ID -> what it should be.
CHECKS = {13890: "Enchant Boots - Minor Speed", 7421: "Runed Copper Rod", 2657: "Smelt Copper"}


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    build = sys.argv[1]
    data = wago.load(wago.folder_from_argv("tomte_recipes_"), TABLES, build)

    parent = {r["ID"]: r["ParentSkillLineID"] for r in data["SkillLine"]}
    profession = {}  # spell -> profession skill line
    for row in data["SkillLineAbility"]:
        line = row["SkillLine"]
        top = int(parent.get(line, "0") or 0) or int(line)
        if top in PROFESSIONS:
            profession.setdefault(int(row["Spell"]), top)

    makes = {}  # recipe spell -> item it makes (0 for an enchant)
    for row in data["SpellEffect"]:
        spell, effect = int(row["SpellID"]), int(row["Effect"])
        if spell not in profession:
            continue
        if effect == CREATE_ITEM:
            makes[spell] = int(row["EffectItemType"] or 0) or makes.get(spell, 0)
        elif effect == ENCHANT_ITEM:
            makes.setdefault(spell, 0)

    by_prof = {}
    for spell, item in makes.items():
        by_prof.setdefault(profession[spell], {})[spell] = item

    lines = ["local addonName, ns = ...", "",
             "-- Generated by tools/recipes.py from the client's spell tables (wago.tools, build %s). Do not edit." % build,
             "-- [profession skill line] = { [recipe spell ID] = item it makes (0: an enchant) }",
             "ns.CHAT_RECIPES = {"]
    for prof in sorted(by_prof):
        lines.append("\t[%d] = {" % prof)
        row = "\t\t"
        for spell in sorted(by_prof[prof]):
            entry = "[%d] = %d, " % (spell, by_prof[prof][spell])
            if len(row.expandtabs(4)) + len(entry) > 118:
                lines.append(row.rstrip())
                row = "\t\t"
            row += entry
        lines.append(row.rstrip())
        lines.append("\t},")
    lines.append("}")
    with open(OUT, "w", encoding="utf-8", newline="\r\n") as f:
        f.write("\n".join(lines) + "\n")
    names = {int(r["ID"]): r["Name_lang"] for r in data["SpellName"]}
    print("wrote %s: %s" % (os.path.normpath(OUT), {p: len(s) for p, s in sorted(by_prof.items())}))
    for spell, expect in CHECKS.items():
        print("  %d %s: %s, makes %s" % (spell, expect, names.get(spell), makes.get(spell)))


if __name__ == "__main__":
    main()
